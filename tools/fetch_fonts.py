"""Download the app's fonts (DM Sans and Noto Sans Devanagari) so they are served from our own
server: faster on slow networks, works offline in the installed app, and no request to Google from users' phones.

    python tools/fetch_fonts.py [frontend_dir]
"""
import re, sys, urllib.request
from pathlib import Path

CSS_URL = ("https://fonts.googleapis.com/css2?family=DM+Sans:opsz,wght@9..40,400;9..40,500;9..40,700;9..40,800"
           "&family=Noto+Sans+Devanagari:wght@400;500;700&display=swap")
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"


def get(url: str) -> bytes:
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=30) as r:
        return r.read()


def main() -> None:
    fe = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "frontend")
    out = fe / "fonts"
    out.mkdir(exist_ok=True)
    css = get(CSS_URL).decode()
    # Keep only the Latin and Devanagari subsets the app needs.
    blocks = re.findall(r"/\* ([\w-]+) \*/\s*(@font-face \{.*?\})", css, re.S)
    kept = []
    for subset, block in blocks:
        if subset not in ("latin", "latin-ext", "devanagari"):
            continue
        url = re.search(r"url\((https://[^)]+)\)", block).group(1)
        name = re.sub(r"[^\w.-]", "_", url.rsplit("/", 1)[-1])
        (out / name).write_bytes(get(url))
        kept.append(block.replace(url, f"/static/fonts/{name}"))
    if not kept:
        raise SystemExit("No fonts found in the Google Fonts response; leaving fonts.css unchanged.")
    (out / "fonts.css").write_text("/* Self-hosted fonts, generated by tools/fetch_fonts.py */\n" + "\n".join(kept) + "\n")
    print(f"saved {len(kept)} font files to {out}")


if __name__ == "__main__":
    main()
